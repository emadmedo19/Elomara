import functools,sys,threading
from http.server import SimpleHTTPRequestHandler,ThreadingHTTPServer
from playwright.sync_api import sync_playwright,expect
class Quiet(SimpleHTTPRequestHandler):
    def log_message(self,*args): pass
server=ThreadingHTTPServer(('127.0.0.1',0),functools.partial(Quiet,directory=sys.argv[1] if len(sys.argv)>1 else '/tmp/elomara-play-billing'))
threading.Thread(target=server.serve_forever,daemon=True).start()
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    for width,height in [(390,844),(1280,900)]:
        page=browser.new_page(viewport={'width':width,'height':height})
        page.goto(f'http://127.0.0.1:{server.server_port}')
        page.get_by_role('button',name='الاشتراك والباقات',exact=True).click()
        expect(page.get_by_role('heading',name='الاشتراك والباقات',exact=True)).to_be_visible()
        expect(page.get_by_text('٩٩٫٠٠ ج.م.',exact=True)).to_be_visible()
        expect(page.get_by_text('٩٩٩٫٠٠ ج.م.',exact=True)).to_be_visible()
        annual=page.get_by_role('radio',name='سنوي',exact=False)
        annual.focus()
        annual.press("Space")
        expect(page.get_by_role('button',name='اشتراك سنوي',exact=True)).to_be_enabled()
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        page.get_by_role('radio',name='شهري',exact=False).press("Space")
        page.locator('summary',has_text='كود خاص أو كود خصم').click()
        page.get_by_label('كود خاص أو كود خصم').fill('elomara50off')
        page.get_by_role('button',name='تطبيق الكود',exact=True).click()
        expect(page.get_by_text('٩٩٫٠٠ ج.م.',exact=True)).to_be_visible()
        assert '49.50' not in page.locator('body').inner_text()
        page.get_by_role('button',name='اشتراك شهري',exact=True).click()
        expect(page.get_by_text('حالة الاشتراك: نشط',exact=True)).to_be_visible()
        expect(page.get_by_role('button',name='اشتراك شهري',exact=True)).to_be_disabled()
        page.get_by_role('button',name='إدارة أو إلغاء الاشتراك',exact=True).click()
        assert page.evaluate('window.state.manageUrl').startswith('https://play.google.com/store/account/subscriptions')
        page.get_by_role('button',name='استعادة المشتريات',exact=True).click()
        expect(page.get_by_text('حالة الاشتراك: نشط',exact=True)).to_be_visible()
        page.get_by_label('كود خاص أو كود خصم').fill('ELM-VIP-'+'A'*24)
        page.get_by_role('button',name='تطبيق الكود',exact=True).click()
        expect(page.get_by_text('حالة الاشتراك: VIP مجاني مدى الحياة',exact=True)).to_be_visible()
        expect(page.get_by_text('اشتراك VIP مجاني مدى الحياة',exact=True)).to_be_visible()
        expect(page.get_by_role('button',name='اشتراك شهري',exact=True)).to_have_count(0)
        expect(page.get_by_role('button',name='اشتراك سنوي',exact=True)).to_have_count(0)
        expect(page.get_by_label('كود خاص أو كود خصم')).to_have_count(0)
        expect(page.get_by_text('14 يوم تجربة مجانية لكل عمارة جديدة. السكان يستخدمون التطبيق مجانًا.',exact=True)).to_have_count(0)
        expect(page.get_by_role('button',name='استعادة المشتريات',exact=True)).to_have_count(0)
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        page.close()
    for scenario,expected in [('old-apk','حدّث التطبيق من Google Play؛ النسخة المثبّتة حاليًا لا تدعم شراء الاشتراكات.'),('disabled','الشراء غير متاح حاليًا. أعد تحميل الباقات بعد إتاحة الخدمة.'),('empty','لم يعرض Google Play باقات لهذا الحساب. تأكد من تثبيت آخر نسخة من المتجر والانضمام للاختبار بنفس حساب Google، ثم أعد تحميل الباقات.')]:
        page=browser.new_page(viewport={'width':390,'height':844})
        page.goto(f'http://127.0.0.1:{server.server_port}?scenario={scenario}')
        page.get_by_role('button',name='الاشتراك والباقات',exact=True).click()
        expect(page.get_by_text(expected,exact=True)).to_be_visible()
        expect(page.get_by_role('button',name='اشتراك شهري',exact=True)).to_have_count(0)
        expect(page.get_by_role('button',name='إعادة تحميل الباقات',exact=True)).to_be_enabled()
        page.evaluate("window.state.scenario='normal'")
        page.get_by_role('button',name='إعادة تحميل الباقات',exact=True).click()
        expect(page.get_by_text('٩٩٫٠٠ ج.م.',exact=True)).to_be_visible()
        expect(page.get_by_role('button',name='اشتراك شهري',exact=True)).to_be_enabled()
        page.close()
    page=browser.new_page(viewport={'width':390,'height':844})
    page.goto(f'http://127.0.0.1:{server.server_port}?status=vip')
    page.get_by_role('button',name='الاشتراك والباقات',exact=True).click()
    expect(page.get_by_text('حالة الاشتراك: VIP مجاني مدى الحياة',exact=True)).to_be_visible()
    expect(page.get_by_text('اشتراك VIP مجاني مدى الحياة',exact=True)).to_be_visible()
    expect(page.get_by_text('٩٩٫٠٠ ج.م.',exact=True)).to_have_count(0)
    expect(page.get_by_text('٩٩٩٫٠٠ ج.م.',exact=True)).to_have_count(0)
    page.close()
    page=browser.new_page(viewport={'width':390,'height':844})
    page.goto(f'http://127.0.0.1:{server.server_port}?role=resident')
    expect(page.get_by_role('button',name='إدارة اشتراكات المنصة',exact=True)).to_have_count(0)
    page.get_by_role('button',name='الاشتراك والباقات',exact=True).click()
    expect(page.get_by_role('button',name='اشتراك شهري',exact=True)).to_have_count(0)
    expect(page.get_by_text('14 يوم تجربة مجانية لكل عمارة جديدة. السكان يستخدمون التطبيق مجانًا.',exact=True)).to_be_visible()
    page.close()
    page=browser.new_page(viewport={'width':390,'height':844})
    page.goto(f'http://127.0.0.1:{server.server_port}?role=owner')
    page.get_by_role('button',name='إدارة اشتراكات المنصة',exact=True).click()
    codes=page.get_by_role('region',name='أكواد اشتراك VIP')
    expect(codes.get_by_text('نص الكود غير محفوظ',exact=False)).to_be_visible()
    codes.get_by_role('button',name='إيقاف',exact=True).click()
    expect(codes.get_by_text('موقوف',exact=True)).to_be_visible()
    expect(page.get_by_text('أكواد متاحة: 0 · مستخدمة: 0')).to_be_visible()
    codes.get_by_role('button',name='إعادة تفعيل',exact=True).click()
    expect(codes.get_by_text('متاح',exact=True)).to_be_visible()
    codes.get_by_role('button',name='حذف',exact=True).click()
    codes.get_by_role('button',name='رجوع',exact=True).click()
    expect(codes.get_by_text('نص الكود غير محفوظ',exact=False)).to_be_visible()
    codes.get_by_role('button',name='حذف',exact=True).click()
    codes.get_by_role('button',name='تأكيد الحذف',exact=True).click()
    expect(codes.get_by_text('مفيش أكواد اشتراك VIP لعرضها.')).to_be_visible()
    codes.get_by_role('button',name='إنشاء كود VIP مجاني',exact=True).click()
    expect(codes.get_by_text('ELM-VIP-'+'B'*24,exact=True)).to_be_visible()
    expect(page.get_by_text('أكواد متاحة: 1 · مستخدمة: 0')).to_be_visible()
    expect(page.get_by_text('عمارة الاختبار',exact=True)).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    browser.close()
server.shutdown()
print('PASS: owner VIP management, paid plans, VIP redemption, founder codes, residents, responsive layout')

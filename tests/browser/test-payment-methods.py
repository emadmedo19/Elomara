import functools
import sys
import threading
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from playwright.sync_api import sync_playwright, expect
class Quiet(SimpleHTTPRequestHandler):
    def log_message(self,*args): pass
server=ThreadingHTTPServer(('127.0.0.1',0),functools.partial(Quiet,directory=sys.argv[1] if len(sys.argv)>1 else '/tmp/elomara-payment-methods'))
threading.Thread(target=server.serve_forever,daemon=True).start()
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    for width,height in [(390,844),(1280,900)]:
        page=browser.new_page(viewport={'width':width,'height':height})
        page.add_init_script("Object.defineProperty(navigator,'clipboard',{value:{writeText:async text=>{window.copied=text}}})")
        page.goto(f'http://127.0.0.1:{server.server_port}')
        expect(page.locator('input[readonly]')).to_have_value('old@instapay')
        page.get_by_role('button',name='إعدادات المدير',exact=True).click()
        page.get_by_label('اسم وسيلة السداد الأساسية',exact=True).fill('إنستا باي العمارة')
        page.get_by_label('عنوان الدفع أو رقم الحساب الأساسي',exact=True).fill('building@instapay')
        page.get_by_role('button',name='+ إضافة وسيلة دفع أخرى',exact=True).click()
        page.get_by_label('اسم وسيلة الدفع الإضافية 1',exact=True).fill('فودافون كاش')
        page.get_by_label('بيانات وسيلة الدفع الإضافية 1',exact=True).fill('01001234567')
        page.get_by_role('button',name='+ إضافة وسيلة دفع أخرى',exact=True).click()
        page.get_by_label('اسم وسيلة الدفع الإضافية 2',exact=True).fill('حساب بنكي')
        page.get_by_label('بيانات وسيلة الدفع الإضافية 2',exact=True).fill('EG001234567890123456789012345')
        page.get_by_role('button',name='حفظ التعديلات',exact=True).click()
        expect(page.get_by_role('heading',name='إعدادات العمارة والتحصيل',exact=True)).to_have_count(0)
        expect(page.get_by_label('عنوان الدفع أو رقم الحساب — إنستا باي العمارة',exact=True)).to_have_value('building@instapay')
        expect(page.get_by_label('عنوان الدفع أو رقم الحساب — فودافون كاش',exact=True)).to_have_value('01001234567')
        expect(page.locator('input[readonly]')).to_have_count(3)
        assert page.evaluate('window.savedSettings.paymentMethods')==['نقدي']
        page.get_by_role('button',name='نسخ بيانات فودافون كاش',exact=True).click()
        page.wait_for_function("window.copied==='01001234567'")
        assert page.evaluate('document.documentElement.scrollWidth')<=width
        page.screenshot(path=f'/tmp/elomara-member-payment-methods-{width}.png')
        page.get_by_role('button',name='إعدادات المدير',exact=True).click()
        page.get_by_role('button',name='حذف وسيلة الدفع الإضافية 1',exact=True).click()
        page.get_by_role('button',name='حفظ التعديلات',exact=True).click()
        expect(page.get_by_role('heading',name='إعدادات العمارة والتحصيل',exact=True)).to_have_count(0)
        expect(page.locator('input[readonly]')).to_have_count(2)
        expect(page.get_by_role('button',name='نسخ بيانات فودافون كاش',exact=True)).to_have_count(0)
        page.get_by_role('button',name='تبديل العمارة',exact=True).click()
        expect(page.locator('input[readonly]')).to_have_value('01009998887')
        page.evaluate("window.delayNext=true;window.dispatchEvent(new Event('elomara-building-settings-updated'))")
        page.wait_for_function('!!window.finishPending')
        page.get_by_role('button',name='تبديل العمارة',exact=True).click()
        expect(page.locator('input[readonly]')).to_have_count(2)
        page.evaluate('window.finishPending()')
        expect(page.get_by_label('عنوان الدفع أو رقم الحساب — إنستا باي العمارة',exact=True)).to_have_value('building@instapay')
        page.evaluate("window.failRead=true;window.dispatchEvent(new Event('elomara-building-settings-updated'))")
        expect(page.get_by_role('button',name='إعادة المحاولة',exact=True)).to_be_visible()
        expect(page.locator('input[readonly]')).to_have_count(0)
        page.evaluate('window.failRead=false')
        page.get_by_role('button',name='إعادة المحاولة',exact=True).click()
        expect(page.locator('input[readonly]')).to_have_count(2)
        page.evaluate("window.store['building-a']={};window.dispatchEvent(new Event('elomara-building-settings-updated'))")
        expect(page.get_by_text('لم يضف مدير العمارة بيانات دفع حتى الآن.',exact=True)).to_be_visible()
        expect(page.locator('input[readonly]')).to_have_count(0)
        print('PASS',width,'legacy destination; manager saves/removes multiple methods; member copies exact wallet number; account switching rejects stale data; errors/retry/empty state; no horizontal overflow')
        page.close()
    app_server=ThreadingHTTPServer(('127.0.0.1',0),functools.partial(Quiet,directory='/tmp/elomara-membership-ui'))
    threading.Thread(target=app_server.serve_forever,daemon=True).start()
    page=browser.new_page(viewport={'width':390,'height':844})
    page.add_init_script("const timer=setTimeout;window.setTimeout=(fn,ms,...args)=>timer(fn,ms===5600?0:ms,...args)")
    page.goto(f'http://127.0.0.1:{app_server.server_port}/?scenario=payment-destinations')
    page.get_by_role('button',name='حسابي المالي',exact=True).click()
    expect(page.get_by_role('heading',name='حسابي المالي وسجل المدفوعات',exact=True)).to_be_visible()
    expect(page.get_by_label('عنوان الدفع أو رقم الحساب — إنستا باي',exact=True)).to_have_value('building@instapay')
    expect(page.get_by_label('عنوان الدفع أو رقم الحساب — محفظة إلكترونية',exact=True)).to_have_value('01001234567')
    page.wait_for_timeout(600)
    page.screenshot(path='/tmp/elomara-actual-member-financial-payment-methods.png')
    page.evaluate("window.mock.paymentResponse={building_id:'another-building',methods:[{name:'Wrong building',account:'not-for-this-user'}]}")
    page.get_by_role('button',name='تحديث وسائل الدفع',exact=True).click()
    expect(page.get_by_role('button',name='إعادة المحاولة',exact=True)).to_be_visible()
    expect(page.locator('input[readonly]')).to_have_count(0)
    assert 'not-for-this-user' not in page.locator('body').inner_text()
    print('PASS actual ResidentPortal: methods render on financial page; response from another building is rejected')
    page.close();app_server.shutdown()
    browser.close()
server.shutdown()

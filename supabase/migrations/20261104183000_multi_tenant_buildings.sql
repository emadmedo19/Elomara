-- Multi-tenant foundation: each customer can own an isolated building.
-- Existing buildings and profile assignments are preserved. No production data is rewritten.

alter table public.profiles
  drop constraint if exists profiles_role_check;

alter table public.profiles
  add constraint profiles_role_check
  check (role = any (array[
    'super_admin'::text,
    'assistant_admin'::text,
    'building_admin'::text,
    'owner'::text,
    'tenant'::text,
    'pending'::text
  ]));

create or replace function public.can_manage_bunyan_building(target_building_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $function$
  select exists (
    select 1
    from public.profiles p
    where p.id = (select auth.uid())
      and p.approved = true
      and (
        p.role = 'super_admin'
        or (
          p.role in ('assistant_admin', 'building_admin')
          and p.building_id = target_building_id
        )
      )
  );
$function$;

-- Invitation codes are UUIDs generated by Postgres and can only be redeemed
-- by an authenticated account whose verified login email matches the invite.
create table if not exists public.building_invites (
  id uuid primary key default gen_random_uuid(),
  building_id uuid not null references public.buildings(id) on delete cascade,
  apartment_id uuid not null references public.apartments(id) on delete cascade,
  invited_email text not null,
  invite_code uuid not null unique default gen_random_uuid(),
  invited_by uuid not null references auth.users(id),
  expires_at timestamptz not null default (now() + interval '7 days'),
  accepted_at timestamptz,
  created_at timestamptz not null default now(),
  constraint building_invites_email_not_empty check (length(trim(invited_email)) > 3)
);

create index if not exists building_invites_building_id_idx
  on public.building_invites(building_id);
create index if not exists building_invites_email_idx
  on public.building_invites(lower(invited_email));

alter table public.building_invites enable row level security;
revoke all on public.building_invites from anon, authenticated;

-- A newly registered customer may create exactly one building for their account.
-- Their profile becomes the building-scoped administrator.
create or replace function public.create_building_for_current_user(
  building_name text,
  building_address text default '',
  units_count integer default 0,
  floors_count integer default null
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $function$
declare
  current_id uuid := auth.uid();
  new_building_id uuid;
  profile_row public.profiles%rowtype;
  email_confirmed_at timestamptz;
begin
  if current_id is null then
    raise exception 'Authentication required';
  end if;
  select u.email_confirmed_at into email_confirmed_at
  from auth.users u where u.id = current_id;
  if email_confirmed_at is null then
    raise exception 'Confirm your email before creating a building';
  end if;
  if nullif(trim(building_name), '') is null then
    raise exception 'Building name is required';
  end if;
  if coalesce(units_count, 0) < 0 or (floors_count is not null and floors_count < 0) then
    raise exception 'Unit and floor counts cannot be negative';
  end if;

  select * into profile_row
  from public.profiles
  where id = current_id
  for update;

  if not found or profile_row.role <> 'pending' or profile_row.approved then
    raise exception 'This account is not eligible to create a building';
  end if;
  if profile_row.building_id is not null then
    raise exception 'This account is already assigned to a building';
  end if;

  insert into public.buildings (name, address, total_units, total_floors, manager_name)
  values (
    trim(building_name),
    coalesce(trim(building_address), ''),
    coalesce(units_count, 0),
    floors_count,
    coalesce(profile_row.full_name, '')
  )
  returning id into new_building_id;

  -- Create real apartment rows so the manager can assign residents immediately.
  if coalesce(units_count, 0) > 0 then
    insert into public.apartments (building_id, unit_number, floor)
    select
      new_building_id,
      units.unit_no::text,
      case
        when coalesce(floors_count, 0) > 0 then
          ceil(units.unit_no::numeric / ceil(units_count::numeric / floors_count::numeric))::integer
        else 1
      end
    from generate_series(1, units_count) as units(unit_no);
  end if;

  update public.profiles
  set role = 'building_admin',
      approved = true,
      building_id = new_building_id,
      apartment_id = null,
      updated_at = now()
  where id = current_id;

  return new_building_id;
end;
$function$;

-- Building administrators can issue a single-use, email-bound apartment invite.
create or replace function public.create_building_invite(
  target_building_id uuid,
  target_apartment_id uuid,
  target_email text
)
returns table(invite_code uuid, expires_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $function$
declare
  normalized_email text := lower(trim(target_email));
  created_code uuid;
  expiry timestamptz;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if not public.can_manage_bunyan_building(target_building_id) then
    raise exception 'Not authorized to manage this building';
  end if;
  if normalized_email !~ '^[^@[:space:]]+@[^@[:space:]]+[.][^@[:space:]]+$' then
    raise exception 'A valid email address is required';
  end if;
  if not exists (
    select 1 from public.apartments a
    where a.id = target_apartment_id and a.building_id = target_building_id
  ) then
    raise exception 'Apartment does not belong to this building';
  end if;

  insert into public.building_invites (
    building_id, apartment_id, invited_email, invited_by
  )
  values (target_building_id, target_apartment_id, normalized_email, auth.uid())
  returning building_invites.invite_code, building_invites.expires_at
  into created_code, expiry;

  return query select created_code, expiry;
end;
$function$;

-- Redeem an invitation only once, only for its intended email and apartment.
create or replace function public.accept_building_invite(target_invite_code uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $function$
declare
  current_id uuid := auth.uid();
  current_email text;
  email_confirmed_at timestamptz;
  invite_row public.building_invites%rowtype;
  apartment_owner boolean;
  profile_row public.profiles%rowtype;
begin
  if current_id is null then
    raise exception 'Authentication required';
  end if;

  select lower(u.email), u.email_confirmed_at into current_email, email_confirmed_at
  from auth.users u where u.id = current_id;
  if email_confirmed_at is null then
    raise exception 'Confirm your email before accepting an invitation';
  end if;

  select * into invite_row
  from public.building_invites i
  where i.invite_code = target_invite_code
    and i.accepted_at is null
    and i.expires_at > now()
  for update;

  if not found then
    raise exception 'Invitation is invalid, expired, or already used';
  end if;
  if current_email is null or current_email <> lower(invite_row.invited_email) then
    raise exception 'This invitation belongs to a different email address';
  end if;

  select * into profile_row
  from public.profiles p where p.id = current_id for update;

  if not found or profile_row.role <> 'pending' or profile_row.approved
     or profile_row.building_id is not null then
    raise exception 'This account is already assigned or is not eligible';
  end if;

  select a.is_owner into apartment_owner
  from public.apartments a
  where a.id = invite_row.apartment_id
    and a.building_id = invite_row.building_id;

  if not found then
    raise exception 'The invited apartment is no longer available';
  end if;

  update public.profiles
  set role = case when apartment_owner then 'owner' else 'tenant' end,
      approved = true,
      building_id = invite_row.building_id,
      apartment_id = invite_row.apartment_id,
      updated_at = now()
  where id = current_id;

  update public.building_invites
  set accepted_at = now()
  where id = invite_row.id;

  return true;
end;
$function$;

-- Building-scoped user list for each manager (does not expose other tenants).
create or replace function public.list_building_users()
returns table (
  user_id uuid,
  email text,
  full_name text,
  role text,
  approved boolean,
  building_id uuid,
  apartment_id uuid,
  registered_at timestamptz,
  disabled_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $function$
declare
  manager_building_id uuid;
  manager_role text;
begin
  select p.building_id, p.role
  into manager_building_id, manager_role
  from public.profiles p
  where p.id = auth.uid() and p.approved = true;

  if manager_role not in ('building_admin', 'assistant_admin', 'super_admin') then
    raise exception 'Not authorized to list building users';
  end if;

  return query
  select p.id, u.email::text, coalesce(p.full_name, ''), p.role,
         p.approved, p.building_id, p.apartment_id, u.created_at, p.disabled_at
  from public.profiles p
  join auth.users u on u.id = p.id
  where (manager_role = 'super_admin' or p.building_id = manager_building_id)
  order by u.created_at desc;
end;
$function$;

